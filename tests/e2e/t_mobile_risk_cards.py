# Mobile risk cards: on phones the risk register shows one card per risk (readable, editable); desktop and PDF keep the table.
import sys, os; sys.path.insert(0, os.path.dirname(__file__))
from harness import *
R = Run(); ensure_server()
vis = lambda pg, sel: pg.evaluate("(s)=>[...document.querySelectorAll(s)].filter(e=>e.offsetParent).length", sel)
with sync_playwright() as p:
    b = p.chromium.launch()
    pg, errs, dl = ctx_for(b, 'crp'); pg.goto(URL); pg.wait_for_timeout(4500)
    pg.evaluate(JS_INC, 'JSA & Risk'); pg.wait_for_timeout(700)
    pg.locator('select:has(option[value=oonpP2NightEventLifter])').first.select_option('oonpP2NightEventLifter')
    pg.evaluate("()=>{const b=[...document.querySelectorAll('button')].find(x=>x.innerText.trim()==='Load'&&x.offsetParent); b&&b.click()}"); pg.wait_for_timeout(1200)
    R.check('desktop: the table shows, the cards don\'t', vis(pg, '[data-risk-register] table') == 1 and vis(pg, '[data-risk-card]') == 0)
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(600)
    n = vis(pg, '[data-risk-card]')
    R.check('phone: one card per risk, table hidden', n == 16 and vis(pg, '[data-risk-register] table') == 0, n)
    R.check('phone: nothing wider than the screen', pg.evaluate("()=>{const c=document.querySelector('[data-risk-cards]');return c.scrollWidth<=c.clientWidth+1 && c.getBoundingClientRect().right<=window.innerWidth+1}"))
    first = pg.locator('[data-risk-card]').first
    R.check('card shows the hazard and both ratings', 'impact' in (first.locator('[data-risk-card-field=hazard]').input_value() or '').lower() or len(first.locator('[data-risk-card-field=hazard]').input_value()) > 5, first.locator('[data-risk-card-field=hazard]').input_value())
    fs = pg.evaluate("()=>parseFloat(getComputedStyle(document.querySelector('[data-risk-card] [data-risk-card-field=riskDescription]')).fontSize)")
    R.check('text is phone-readable (15px)', fs >= 15, fs)
    first.locator('[data-risk-card-field=additionalControls]').fill('Spotter at each path entry')
    first.locator('[data-risk-card-pick=resC] select').select_option('E'); pg.wait_for_timeout(400)
    pg.set_viewport_size({'width': 1400, 'height': 950}); pg.wait_for_timeout(600)
    row = pg.locator('[data-risk-register] tbody tr').first
    R.check('edits on the phone show in the desktop table', 'Spotter at each path entry' in row.inner_text() and 'E' in row.locator('[data-risk-pick=resC]').inner_text())
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(400)
    pg.click('[data-risk-card-add]'); pg.wait_for_timeout(400)
    R.check('Add risk adds a card', vis(pg, '[data-risk-card]') == 17)
    pg.locator('[data-risk-card]').last.locator('[data-risk-card-remove]').click(); pg.wait_for_timeout(400)
    R.check('Remove takes it away', vis(pg, '[data-risk-card]') == 16)
    # (the PDF has its own layout, built separately, so it's unaffected by this screen-only change)
    pg.screenshot(path='/tmp/claude-0/v738_phone.png')
    R.check('no page errors', not errs, errs[:3])
    b.close()
R.done()
